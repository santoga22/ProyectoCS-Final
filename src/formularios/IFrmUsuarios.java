    public void LlenarLista(String buscar){
        DefaultTableModel modelo = (DefaultTableModel)this.tblUsuarios.getModel();
        modelo.setRowCount(0);
        
       if(lista.isEmpty()){
           lista=UsuarioDAO.listar();
       }
        
        for(Usuario u : lista){
            
            boolean encontrado = true;
            
            if (!u.getCorreo().toLowerCase().contains(buscar)){
                
                encontrado = false;
            }

            if (encontrado) {
                Object[] fila = new Object[]{
                    u.isActivo(),
                    u.getCorreo()

                };
                modelo.addRow(fila);
            }

        }
    }

