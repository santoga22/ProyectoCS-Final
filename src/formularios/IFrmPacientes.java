    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        FrmAgregarPaciente fagregar = new FrmAgregarPaciente();
        if (id >0){ 
        Paciente p = PacienteDAO.buscarID(id);
        fagregar.id=id;
        fagregar.txtCedula.setText(p.getCedula());
        fagregar.txtGenero.setText(p.getGenero());
        fagregar.txtNombre.setText(p.getNombre());
        fagregar.txtApellidos.setText(p.getApellidos());
        fagregar.txtCorreo.setText(p.getCorreo());
        fagregar.txtTelefono.setText(p.getTelefono());
    
        fagregar.show();
        ClsGlobales.fprincipal.enable(false);   
        }else{ 
            JOptionPane.showMessageDialog(
                null, 
                "Seleccione un paciente de la lista",
                "Error!",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnEditarActionPerformed

