    private String ValidarCampos(Receta r){
      String error = "";
    
      if(
              r.getMedicamento().isEmpty() ||
              r.getCantidad().isEmpty() ||              
              r.getNombrepaciente().isEmpty() ||
              r.getFechaentrega().isEmpty()||
              r.getFarmacia().isEmpty()||
              r.getEstado().isEmpty()
    
      ){
          error = "Por favor ingrese todos los datos";
    
    }
    
    return error;

   
}
