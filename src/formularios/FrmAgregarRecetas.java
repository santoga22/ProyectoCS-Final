    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        this.setAlwaysOnTop(false);
        
        Receta miReceta = new Receta(        
        this.txtMedicamento.getText(), 
        this.txtCantidad.getText(),
        this.txtNombre.getText(),
        this.txtFecha.getText(),
        this.txtFarmacia.getText(),
        this.txtEstado.getText()
       );
            String error = this.ValidarCampos(miReceta);
            
            if(error.isEmpty()){ 
                
                boolean procesado = false;
                if(id ==0){
                    
                    procesado= RecetaDAO.insertar(miReceta);
                    
                }else{
                    procesado= RecetaDAO.actualizar(miReceta,id);
                    
                }
                
                if(procesado){
                    ClsGlobales.frecetas.lista = new ArrayList<Receta> ();
                    ClsGlobales.frecetas.LlenarLista("");
                    this.dispose();
                }
                else {
                     this.setAlwaysOnTop(true);
                }
            }else {
            JOptionPane.showMessageDialog(
                    null,
                    error,
                    "Error!",
                    JOptionPane.ERROR_MESSAGE
            );
             this.setAlwaysOnTop(true);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

