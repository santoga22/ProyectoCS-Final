    public void LlenarLista(String buscar){
        DefaultTableModel modelo = (DefaultTableModel)this.tblDiagnosticos.getModel();
        modelo.setRowCount(0);
        
       if(lista.isEmpty()){
           lista=DiagnosticoDAO.listar();
       }
        
        for(Diagnostico d : lista){
            
            boolean encontrado = true;
            
            if (
                    !d.getEnfermedad().toLowerCase().contains(buscar) && 
                    !d.getSeveridad().toLowerCase().contains(buscar)&&                     
                    !d.getNombrepaciente().toLowerCase().contains(buscar)&& 
                    !d.getFechadiagnostico().toLowerCase().contains(buscar)&& 
                    !d.getHospital().toLowerCase().contains(buscar)&& 
                    !d.getTratamiento().toLowerCase().contains(buscar)
                    
                    ){
                
                encontrado = false;
            }

            if (encontrado) {
                Object[] fila = new Object[]{
                    d.getId(),
                    d.getEnfermedad(),
                    d.getSeveridad(),
                    d.getNombrepaciente(),
                    d.getFechadiagnostico(),
                    d.getHospital(),
                    d.getTratamiento()

                };
                modelo.addRow(fila);
            }

        }
    }

