    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        FrmAgregarDiagnostico fagregar = new FrmAgregarDiagnostico();
        if (id >0){ 
        Diagnostico d = DiagnosticoDAO.buscarID(id);
        fagregar.id=id;
        fagregar.txtEnfermedad.setText(d.getEnfermedad());
        fagregar.txtSeveridad.setText(d.getSeveridad());
        fagregar.txtNombre.setText(d.getNombrepaciente());
        fagregar.txtFecha.setText(d.getFechadiagnostico());
        fagregar.txtHospital.setText(d.getHospital());
        fagregar.txtTratamiento.setText(d.getTratamiento());
    
        fagregar.show();
        ClsGlobales.fprincipal.enable(false);   
        }else{ 
            JOptionPane.showMessageDialog(
                null, 
                "Seleccione un diagnóstico de la lista",
                "Error!",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnEditarActionPerformed

