    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String error = this.validarCampos();
        
     if (error.isEmpty()) {
         //registro
         try {
             
             String salt = ClsEncriptar.generarSalt();
             String clave = ClsEncriptar.encriptaSHA256(this.TxtClave.getText(), salt);
             int idFuncionario = Integer.parseInt(this.TxtIdFuncionario.getText());
             Usuario usuario = new Usuario(
                     this.txtCorreo.getText(),
                     clave,
                     salt,
                     this.TxtNombre.getText(),
                     idFuncionario
             );
             if (UsuarioDAO.insertar(usuario)) {
                 this.dispose();
             }
         }catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "El ID del funcionario debe ser un número entero.");
    
}
         

            
     }else{
            JOptionPane.showMessageDialog(
                    null,
                    error,
                    "Error!",
                    JOptionPane.ERROR_MESSAGE
            );         
     }        
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

