    private void btnCambiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCambiarActionPerformed
     String correo = txtCorreo.getText().trim();
    String nueva = TxtNueva.getText().trim();

    // Validaciones básicas
    if (correo.isEmpty() || nueva.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Debe completar todos los campos.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (nueva.length() < 6) {
        JOptionPane.showMessageDialog(this, "La contraseña debe tener al menos 6 caracteres.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        // Verificar que el correo exista
        if (!UsuarioDAO.existeCorreo(correo)) {
            JOptionPane.showMessageDialog(this, "El correo ingresado no existe en el sistema.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Si existe, generamos nuevo salt y clave encriptada
        String nuevoSalt = ClsEncriptar.generarSalt();
        String nuevaClave = ClsEncriptar.encriptaSHA256(nueva, nuevoSalt);

        boolean actualizado = UsuarioDAO.actualizarClave(correo, nuevaClave, nuevoSalt);

        if (actualizado) {
            JOptionPane.showMessageDialog(this, "Contraseña actualizada correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
            new FrmLogin().setVisible(true);
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo actualizar la contraseña.", "Error", JOptionPane.ERROR_MESSAGE);
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cambiar la contraseña: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnCambiarActionPerformed

