    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        this.setAlwaysOnTop(false);
        
        Paciente miPaciente = new Paciente(        
        this.txtCedula.getText(), 
        this.txtGenero.getText(),
        this.txtNombre.getText(),
        this.txtApellidos.getText(),
        this.txtCorreo.getText(),
        this.txtTelefono.getText()
       );
            String error = this.ValidarCampos(miPaciente);
            
            if(error.isEmpty()){ 
                
                boolean procesado = false;
                if(id ==0){
                    
                    procesado= PacienteDAO.insertar(miPaciente);
                    
                }else{
                    procesado= PacienteDAO.actualizar(miPaciente,id);
                    
                }
                
                if(procesado){
                    ClsGlobales.fpacientes.lista = new ArrayList<Paciente> ();
                    ClsGlobales.fpacientes.LlenarLista("");
                    this.dispose();
                }
                else {
                     this.setAlwaysOnTop(true);
                }
            }else {
            JOptionPane.showMessageDialog(
                    null,
                    error,
                    "Error!",
                    JOptionPane.ERROR_MESSAGE
            );
             this.setAlwaysOnTop(true);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

