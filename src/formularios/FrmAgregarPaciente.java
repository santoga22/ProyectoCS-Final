    private String ValidarCampos(Paciente p){
      String error = "";
    
      if(
              p.getCedula().trim().length() < 11 ||
              p.getGenero().isEmpty() ||              
              p.getNombre().isEmpty() ||
              p.getApellidos().isEmpty()||
              p.getCorreo().isEmpty()||
              p.getTelefono().trim().length() <9
    
      ){
          error = "Por favor ingrese todos los datos";
    
    }
    
    return error;

   
}
